pub fn translate(locale: Locale, key: T) -> &'static str {
    let key_name = key.as_str();
    resources(locale)
        .get(key_name)
        .map(String::as_str)
        .unwrap_or(key_name)
}

fn resources(locale: Locale) -> &'static HashMap<String, String> {
    static EN: OnceLock<HashMap<String, String>> = OnceLock::new();
    static TR: OnceLock<HashMap<String, String>> = OnceLock::new();

    match locale {
        Locale::En => EN.get_or_init(|| parse_resource(include_str!("resources/en.json"))),
        Locale::Tr => TR.get_or_init(|| parse_resource(include_str!("resources/tr.json"))),
    }
}

fn parse_resource(source: &str) -> HashMap<String, String> {
    serde_json::from_str(source).expect("localization resource must be valid JSON")
}
